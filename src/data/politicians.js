export function getPoliticianById(id) {
  return POLITICIANS_DATA.find(p => p.id === id) || POLITICIANS_DATA[0];
}

export function searchPoliticians(query) {
  if (!query || !query.trim()) return POLITICIANS_DATA;
  
  // Parse compound queries e.g. "finance minister and asiedu nketia" or "bawumia, mahama"
  const rawTerms = query
    .split(/\s+(?:and|or|vs|\&|\+)\s+|,\s*/i)
    .map(t => t.trim().toLowerCase())
    .filter(t => t.length > 0);

  if (rawTerms.length === 0) return POLITICIANS_DATA;

  return POLITICIANS_DATA.filter(p => {
    const searchable = [
      p.name,
      p.role,
      p.party,
      p.affiliation,
      ...(p.aliases || []),
      ...(p.dominantTopics || [])
    ].join(' ').toLowerCase();

    return rawTerms.some(term => searchable.includes(term));
  });
}
