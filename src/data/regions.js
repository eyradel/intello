export function normalizeRegionName(rawName) {
  if (!rawName) return '';
  const cleaned = rawName
    .replace(/\s+region$/i, '')
    .trim()
    .toLowerCase();
  
  const map = {
    'greater accra': 'greater-accra',
    'accra': 'greater-accra',
    'ashanti': 'ashanti',
    'kumasi': 'ashanti',
    'eastern': 'eastern',
    'central': 'central',
    'western': 'western',
    'western north': 'western-north',
    'bono': 'bono',
    'ahafo': 'ahafo',
    'bono east': 'bono-east',
    'oti': 'oti',
    'volta': 'volta',
    'northern': 'northern',
    'savannah': 'savannah',
    'north east': 'north-east',
    'upper east': 'upper-east',
    'upper west': 'upper-west'
  };

  return map[cleaned] || cleaned.replace(/\s+/g, '-');
}

export function getRegionById(id) {
  return REGIONS_DATA.find(r => r.id === id) || REGIONS_DATA[0];
}

export function getRegionByShapeName(shapeName) {
  const normId = normalizeRegionName(shapeName);
  return REGIONS_DATA.find(r => r.id === normId) || REGIONS_DATA[0];
}
